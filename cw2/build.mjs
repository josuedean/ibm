import { readFile, writeFile } from 'node:fs/promises';

const modules = ['config.js', 'geometry.js', 'noise.min.js', 'player.js', 'tcw.js',
  'game.js', 'world.js', 'hud.js', 'input.js', 'main.js'];
const root = new URL('./', import.meta.url);
let script = '// Generated by build.mjs. Edit the individual source modules.\n';
for (const filename of modules) {
  const source = (await readFile(new URL(filename, root), 'utf8'))
    .replace(/^import\s[\s\S]*?;\s*$/gm, '')
    .replace(/^export default[^\n]*$/gm, '')
    .replace(/^export (class|const|function) /gm, '$1 ');
  script += '\n// ' + filename + '\n' + source;
}
const css = await readFile(new URL('styles.css', root), 'utf8');
const shell = await readFile(new URL('tcw2.html', root), 'utf8');
const output = shell
  .replace('<link rel="stylesheet" href="./styles.css">', '<style>\n' + css + '</style>')
  .replace('<script type="module" src="./main.js"></script>',
    '<script type="module">\n' + script.replaceAll('</script', '<\\/script') + '</script>');
await writeFile(new URL('Constant_Walker_Playable.html', root), output);
console.log('Built Constant_Walker_Playable.html (no external dependencies).');
